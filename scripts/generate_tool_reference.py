"""Generate docs/MCP_TOOLS.md from the tool schemas rf-mcp publishes.

The reference is built from what an MCP client receives (`list_tools`), so names,
descriptions, parameter types, enums, defaults and annotations cannot drift from the
code. tests/test_tool_reference.py fails when the committed file is out of date.

Usage: uv run python scripts/generate_tool_reference.py [--out docs/MCP_TOOLS.md] [--check]
"""

from __future__ import annotations

import argparse
import asyncio
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = ROOT / "docs" / "MCP_TOOLS.md"

HEADER = """# MCP tool reference

Generated by `scripts/generate_tool_reference.py` from the schemas the server publishes; do not edit by hand.
Regenerate with `uv run python scripts/generate_tool_reference.py`.

The `rf_*` tools share these parameters (`rf_diagnose` takes only `root`):

- `root` is the project folder (with `robot.toml`); without it the server's `--root` is used.
- `profile` applies a `robot.toml` profile (`-p`).
- `target` overrides the execution mode for one call: `server` runs robotcode on the MCP host, `client` returns
  the command for the agent's own shell (see [Execution modes](CONFIGURATION.md#execution-modes)).
- `shell` picks the syntax of client-mode commands (`powershell` or `bash`).

Arguments that are empty (`""`, `[]`, `{}`, `"[]"`, `"null"`) count as not set, and list arguments also accept a
JSON array string, a Python list string or a comma-separated string.
"""


def _type_of(schema: dict[str, Any]) -> str:
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if "anyOf" in schema:
        parts = [_type_of(s) for s in schema["anyOf"] if s.get("type") != "null"]
        return " \\| ".join(parts) or "null"
    kind = schema.get("type", "any")
    if kind == "array":
        return f"list of {_type_of(schema.get('items', {}))}"
    if kind == "object":
        extra = schema.get("additionalProperties")
        return f"object of {_type_of(extra)}" if isinstance(extra, dict) else "object"
    return str(kind)


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _default(schema: dict[str, Any], required: bool) -> str:
    if required:
        return "required"
    if "default" not in schema or schema["default"] is None:
        return ""
    value = schema["default"]
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    return f"`{value}`"


_COMMON = ("root", "profile", "target", "shell")


def _field(obj: Any, snake: str, camel: str) -> Any:
    """Read an MCP type field by its MCP SDK v2 name (FastMCP 4) or, before that, its v1 name (FastMCP 3)."""
    return getattr(obj, snake if snake in type(obj).model_fields else camel)


def _annotations(tool: Any) -> str:
    ann = tool.annotations
    if ann is None:
        return ""
    flags = [name for name, value in (
        ("read-only", _field(ann, "read_only_hint", "readOnlyHint")),
        ("destructive", _field(ann, "destructive_hint", "destructiveHint")),
        ("idempotent", _field(ann, "idempotent_hint", "idempotentHint")),
        ("open world", _field(ann, "open_world_hint", "openWorldHint")),
    ) if value]
    return ", ".join(flags) or "none"


def render(tools: list[Any], templates: list[Any]) -> str:
    lines = [HEADER, "## Tools", ""]
    rf_tools = [t for t in tools if t.name.startswith("rf_")]
    other = [t for t in tools if not t.name.startswith("rf_")]
    lines += ["| tool | use when |", "| --- | --- |"]
    for tool in rf_tools:
        first = (tool.description or "").split(" - ")[0].split(". ")[0]
        lines.append(f"| [`{tool.name}`](#{tool.name}) | {_cell(first.removeprefix('Use when '))} |")
    lines.append("")
    for tool in rf_tools:
        schema = _field(tool, "input_schema", "inputSchema") or {}
        props = schema.get("properties", {})
        required = set(schema.get("required", []))
        lines += [f"### `{tool.name}`", "", _cell(tool.description or ""), "",
                  f"Annotations: {_annotations(tool)}.", ""]
        own = [(n, p) for n, p in props.items() if n not in _COMMON]
        if own:
            lines += ["| parameter | type | default | description |", "| --- | --- | --- | --- |"]
            for name, prop in own:
                lines.append(f"| `{name}` | {_type_of(prop)} | {_default(prop, name in required)} | "
                             f"{_cell(prop.get('description', ''))} |")
            lines.append("")
        common = [n for n in _COMMON if n in props]
        if common:
            lines += [f"Common parameters: {', '.join(f'`{n}`' for n in common)}.", ""]
    if other:
        lines += ["## Skill resources", "",
                  "Skills are served as MCP resources (`skill://<name>/SKILL.md`, with reference files under "
                  "`skill://<name>/references/...`). Agents that cannot read resources use these two tools:", ""]
        for tool in other:
            lines.append(f"- `{tool.name}`: {_cell((tool.description or '').splitlines()[0])}")
        lines.append("")
        if templates:
            lines += ["Resource templates of the built-in skills: "
                      + ", ".join(f"`{u}`" for u in sorted(_field(t, "uri_template", "uriTemplate") for t in templates)) + ".", ""]
    return "\n".join(lines).rstrip() + "\n"


async def collect() -> tuple[list[Any], list[Any]]:
    from fastmcp.client import Client

    from robotmcp.config import ServerConfig
    from robotmcp.server import create_server

    with tempfile.TemporaryDirectory() as root:
        cfg = ServerConfig.from_env_and_args(argv=["--mode", "server", "--root", root], env={})
        async with Client(create_server(cfg)) as client:
            return list(await client.list_tools()), list(await client.list_resource_templates())


def generate() -> str:
    return render(*asyncio.run(collect()))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is out of date")
    args = parser.parse_args()
    text = generate()
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current != text:
            print(f"{args.out} is out of date; run scripts/generate_tool_reference.py", file=sys.stderr)
            return 1
        return 0
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
