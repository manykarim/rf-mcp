"""OpenTelemetry tracing and metrics instrumentation for rf-mcp."""

from __future__ import annotations

import os
import time
from contextlib import contextmanager
from dataclasses import dataclass, field
from typing import Any, Iterator

from opentelemetry import metrics, trace
from opentelemetry.trace import Span, Status, StatusCode

TRACER_NAME = "rf-mcp"
METER_NAME = "rf-mcp"


@dataclass
class _Instruments:
    commands_total: Any
    command_duration_ms: Any
    hints_generated: Any
    skills_read: Any


_instruments_cache: dict[int, _Instruments] = {}


def _get_instruments() -> _Instruments:
    provider = metrics.get_meter_provider()
    key = id(provider)
    cached = _instruments_cache.get(key)
    if cached is not None:
        return cached
    meter = metrics.get_meter(METER_NAME)
    inst = _Instruments(
        commands_total=meter.create_counter(
            "rf_mcp.commands.total",
            description="Total robotcode CLI and session operations invoked via rf-mcp",
        ),
        command_duration_ms=meter.create_histogram(
            "rf_mcp.command.duration_ms",
            unit="ms",
            description="Execution duration of rf-mcp operations in milliseconds",
        ),
        hints_generated=meter.create_counter(
            "rf_mcp.hints.generated",
            description="Total actionable recovery hints generated by HintEngine",
        ),
        skills_read=meter.create_counter(
            "rf_mcp.skills.read",
            description="Total skill resources read via rf-mcp",
        ),
    )
    _instruments_cache[key] = inst
    return inst


def get_tracer() -> trace.Tracer:
    """Return the OpenTelemetry tracer for rf-mcp."""
    return trace.get_tracer(TRACER_NAME)


@dataclass
class SpanTracker:
    """Mutable tracker yielded inside `record_operation` so callers can set exit codes and hint counts."""

    span: Span
    operation: str
    execution_mode: str
    profile: str | None = None
    exit_code: int = 0
    hints_count: int = 0
    extra_attributes: dict[str, Any] = field(default_factory=dict)

    def set_result(
        self,
        *,
        exit_code: int = 0,
        hints_count: int = 0,
        status: str | None = None,
    ) -> None:
        self.exit_code = exit_code
        self.hints_count = hints_count
        self.span.set_attribute("rf_mcp.exit_code", int(exit_code))
        self.span.set_attribute("rf_mcp.hints_count", int(hints_count))
        if status:
            self.span.set_attribute("rf_mcp.status", status)
        if exit_code not in (0, 124):
            self.span.set_status(Status(StatusCode.ERROR, f"exit_code={exit_code}"))


@contextmanager
def record_operation(
    span_name: str,
    *,
    operation: str,
    execution_mode: str = "server",
    profile: str | None = None,
    attributes: dict[str, Any] | None = None,
) -> Iterator[SpanTracker]:
    """Record an OpenTelemetry span and command/duration/hint metrics for an rf-mcp operation."""
    tracer = get_tracer()
    inst = _get_instruments()
    full_span_name = (
        span_name if span_name.startswith("rf_mcp.") else f"rf_mcp.{span_name}"
    )
    start_ns = time.perf_counter_ns()
    with tracer.start_as_current_span(full_span_name) as span:
        span.set_attribute("rf_mcp.operation", operation)
        span.set_attribute("rf_mcp.execution_mode", execution_mode)
        if profile:
            span.set_attribute("rf_mcp.profile", profile)
        if attributes:
            for k, v in attributes.items():
                if v is not None:
                    span.set_attribute(k, v)
        tracker = SpanTracker(
            span=span,
            operation=operation,
            execution_mode=execution_mode,
            profile=profile,
        )
        try:
            yield tracker
        except Exception as exc:
            tracker.exit_code = -1
            span.record_exception(exc)
            span.set_status(Status(StatusCode.ERROR, str(exc)))
            raise
        finally:
            elapsed_ms = (time.perf_counter_ns() - start_ns) / 1_000_000.0
            span.set_attribute("rf_mcp.exit_code", int(tracker.exit_code))
            span.set_attribute("rf_mcp.hints_count", int(tracker.hints_count))
            metric_attrs = {
                "operation": operation,
                "mode": execution_mode,
                "exit_code": int(tracker.exit_code),
            }
            inst.commands_total.add(1, metric_attrs)
            inst.command_duration_ms.record(elapsed_ms, metric_attrs)
            if tracker.hints_count > 0:
                inst.hints_generated.add(
                    int(tracker.hints_count),
                    {"operation": operation, "mode": execution_mode},
                )


def record_hints_generated(
    count: int, *, operation: str = "diagnose", execution_mode: str = "server"
) -> None:
    """Increment the `rf_mcp.hints.generated` counter explicitly."""
    if count > 0:
        _get_instruments().hints_generated.add(
            int(count),
            {"operation": operation, "mode": execution_mode},
        )


def record_skill_read(skill_name: str) -> None:
    """Record a skill read event in OpenTelemetry metrics and trace span."""
    inst = _get_instruments()
    inst.skills_read.add(1, {"skill": skill_name})
    with get_tracer().start_as_current_span("rf_mcp.skill.read") as span:
        span.set_attribute("rf_mcp.skill", skill_name)


def configure_otel(
    endpoint: str | None = None,
    service_name: str = "rf-mcp",
) -> bool:
    """Configure OpenTelemetry SDK TracerProvider and MeterProvider with OTLP exporters if endpoint is set.

    Returns True if the OTel SDK was configured, or False when running in zero-overhead no-op mode.
    """
    resolved_endpoint = endpoint or os.environ.get("OTEL_EXPORTER_OTLP_ENDPOINT")
    if not resolved_endpoint:
        return False

    try:
        from opentelemetry.exporter.otlp.proto.http.metric_exporter import (
            OTLPMetricExporter,
        )
        from opentelemetry.exporter.otlp.proto.http.trace_exporter import (
            OTLPSpanExporter,
        )
        from opentelemetry.sdk.metrics import MeterProvider
        from opentelemetry.sdk.metrics.export import PeriodicExportingMetricReader
        from opentelemetry.sdk.resources import Resource
        from opentelemetry.sdk.trace import TracerProvider
        from opentelemetry.sdk.trace.export import BatchSpanProcessor
    except ImportError:
        return False

    resource = Resource.create({"service.name": service_name})

    base = resolved_endpoint.rstrip("/")
    traces_url = base if base.endswith("/v1/traces") else f"{base}/v1/traces"
    metrics_url = base if base.endswith("/v1/metrics") else f"{base}/v1/metrics"

    tracer_provider = TracerProvider(resource=resource)
    tracer_provider.add_span_processor(
        BatchSpanProcessor(OTLPSpanExporter(endpoint=traces_url))
    )
    trace.set_tracer_provider(tracer_provider)

    metric_reader = PeriodicExportingMetricReader(
        OTLPMetricExporter(endpoint=metrics_url)
    )
    meter_provider = MeterProvider(
        resource=resource, metric_readers=[metric_reader]
    )
    metrics.set_meter_provider(meter_provider)
    return True
